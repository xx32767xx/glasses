package com.leion.lanrelay;

/**
 * TtsFeature —— 「把译文念出来」这个能力的总开关（5.38 立的，5.152 打开）。
 * ============================================================================
 * **现在是开着的**。5.38 时用户定「这个功能先不使用」，于是这里返回 false，
 * 三处入口（房间页不建队列、翻译官页「朗读」块不显示、设置页不显示开关）随之一致消失。
 * 5.152 老师要求加上播报，这里改回 true。
 *
 * <p>为什么保留这个类、而不是删掉后在三个页面各写一份：
 * <ol>
 *   <li>**只有一个开关**：要临时关掉改一处，三处入口一起消失 —— 不会出现
 *       "房间页在念、翻译官页却没有开关"这种半开状态（半开是最难查的）；</li>
 *   <li>测试钉着这条：{@code tests/tts-suite.mjs} 检查"开关只有一处"，
 *       且两个页面都按它决定是否建队列。</li>
 * </ol>
 *
 * <p>念**译文**还是念**原文**不在这里 —— 那是每次朗读时的选择（5.152），
 * 见房间页底部的「朗读 · 译文/原文」开关与偏好 {@code ttsReadOriginal}。
 *
 * <p>历史（5.38）：当时用户定「这个功能先不使用」，于是 {@link #enabled()} 返回 false，
 * 但**实现一行没删**（合成 → 只在耳机上播 → 队列策略 → 与实时传声互斥全都做好了）。
 * 同时**没有**采用同事那套 `qwen3-tts-flash` 云端合成：要 Key + 外网 + 按句计费，
 * 而且他的链路是"合成 → 拿音频地址 → 再下载"两次 HTTP，延迟叠加在已经 1~2 秒的
 * 翻译后面；音质确实更好，但那是一个"接入云服务"的决定（Key/账单/隐私/SLA），
 * 不是搬一段代码。这些判断记在 docs/21 §5.30 里。
 */
public final class TtsFeature {

    private TtsFeature() {
    }

    /**
     * 播报功能是否开启。
     *
     * <p>⚠️ 两个页面都按它决定要不要建 {@link TtsQueue}；关掉时三处
     * （房间页队列 / 翻译官页配置行 / 朗读开关）必须同时消失 —— 有测试钉着。
     */
    public static boolean enabled() {
        return true;
    }
}
