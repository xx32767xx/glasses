package com.leion.lanrelay;

/**
 * TtsFeature —— 「把译文念出来」这个能力的总开关（5.38）。
 * ============================================================================
 * **现在是关着的**。用户 2026-11 定：「这个功能先不使用」。
 *
 * <p>为什么留代码、不留入口：这一层（合成 → 只在耳机/眼镜上播 → 队列策略 →
 * 与实时传声互斥）已经做完并有测试，**关掉只关"能不能用"，不删实现**。
 * 将来要开，改这一个常量，三处入口（设置页一行、房间页、翻译官页配置）自动回来 ——
 * 不会出现"半开"的状态（半开最难受：有开关但行为不一致）。
 *
 * <p><b>为什么不用同事那套云端 TTS</b>（他那边是 `qwen3-tts-flash` + 音色克隆）：
 * <ol>
 *   <li>**合并冻结**：我们说好只借思路、不借代码，所以他的实现进不来；</li>
 *   <li>那是**云端付费服务**：要 DashScope Key + 外网，而且他的链路是"合成 → 拿音频地址 →
 *       再下载 → 规整 wav"两次 HTTP。我们 relay 现在**没有**任何大模型/TTS 客户端，
 *       加这条路等于新开一条外部依赖 + Key 管理 + 限流 + 重试 + 计费；</li>
 *   <li>**延迟叠加**：同传已经是"说完一句 1~2 秒出译文"，再叠一次云端合成，
 *       用户听到的是更晚的话；本地引擎首包在几百毫秒级；</li>
 *   <li>**成本是持续的**：按句云端合成，一场三十分钟几百句，是长期账单；</li>
 *   <li>**音色克隆带合规义务**（他那边就有一句"请确认对方已同意录音用于本次音色生成"），
 *       配套的授权流程我们没有；</li>
 *   <li>**他的方案确实更好听**：巴葡发音、自然度、可克隆音色都强于安卓本机引擎。
 *       如果哪天要做"像真人的播报"，他的路线是对的 —— 但那是一个**接入云服务**的决定
 *       （Key、账单、隐私、SLA），不是搬一段代码，要单独拍板。</li>
 * </ol>
 *
 * <p>所以现在的位置是：**字幕优先**（这对我们这套眼镜/耳机场景本来就够用），
 * 播报整层先停在这里，等"要不要接云端音色"这件事真的要做时再开。
 */
public final class TtsFeature {

    private TtsFeature() {
    }

    /**
     * 播报功能是否开启。
     *
     * <p>⚠️ 关着的时候三个地方必须一致（有测试钉着）：
     * 设置页不显示开关、房间页不建队列、翻译官「配置」不显示朗读那一行。
     */
    public static boolean enabled() {
        return false;
    }
}
