package com.rokid.cxr.sample.model.selfView

/** Doc reference: chapter 08 custom page (openCustomView JSON: type, props, children). 文档参考：第 08 章自定义页面（openCustomView JSON：type、props、children）。 */
/**
 * Custom view tree node model.
 * 自定义视图树节点模型。
 *
 * Describes full page by recursive `children` tree
 * and serializes to CXR custom-view protocol JSON.
 * 通过递归的 `children` 树描述完整页面，并序列化为 CXR 自定义视图协议 JSON。
 */
class SelfViewJson {
    // Node type, e.g. LinearLayout/TextView/ImageView. 节点类型，例如 LinearLayout/TextView/ImageView。
    var type: String = ""
    // Node props as valid JSON string (generated by *Props.toJson()). 节点 props，为合法 JSON 字符串（由 *Props.toJson() 生成）。
    var props: String = ""
    // Child node list that recursively builds the full view tree. 子节点列表，递归构建完整视图树。
    var children: List<SelfViewJson>? = null

    /**
     * Serializes current node and its children.
     * 序列化当前节点及其子节点。
     */
    fun toJson(): String {
        return if (type.isEmpty()){
            throw Exception("type is empty")
        }else{
            // Serialize to SDK structure: {"type":"...","props":{...},"children":[...]} 序列化为 SDK 结构：...
            val rb = StringBuilder("{").append("\"type\":\"$type\"")
                .append(",\"props\":$props")
            children?.let {
                rb.append(",\"children\":[")
                for (child in children!!){
                    rb.append(child.toJson())
                    rb.append(",")
                }
                rb.deleteCharAt(rb.length - 1)
                rb.append("]")
            }
            rb.append("}")
            rb.toString()
        }
    }
}
