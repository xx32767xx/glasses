                    layout_width = "wrap_content"
                    layout_height = "wrap_content"
                    text = "Hello CXR-L"
                    textSize = "16sp"
                    textColor = "#FF00FF00"
                }.toJson()
            },
            SelfViewJson().apply {
                type = "TextView"
                props = TextViewProps().apply {
                    id = "subtitle_text"
                    layout_width = "wrap_content"
                    layout_height = "wrap_content"
                    text = "CXR-L CustomView Demo"
                    textSize = "12sp"
                    textColor = "#FF00FF00"
                }.toJson()
            }
        )
    }.toJson()
}
