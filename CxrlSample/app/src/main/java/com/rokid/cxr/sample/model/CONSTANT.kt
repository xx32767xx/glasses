     * - Output is **compact single-line JSON** (important: the glasses-side parser expects compact
     *   format; multi-line indented JSON causes `customView_open` to fail silently—a difference
     *   verified on real devices in the 1.0.4 Sample)
     * - `id` is placed inside `props` (guaranteed by the setter)
     * - `textSize` automatically appends `sp`, and dimensions automatically append `dp`
     *   (validated by the setter)
     * - Colors use green-screen processing (8-bit ARGB: green `#FF00FF00` for the green-light
     *   screen, `#FF000000` for the background)
     *
     * This is the single source of truth for the entire project (N-P1-3): referenced by
     * 02 Quick Start, 05 Android Docs, and the built-in Sample.
     * Validated by [com.rokid.cxr.sample.model.CustomViewJsonValidator.validateViewData].
     *
     * Note: this template does not use icons (the glasses side renders normally when viewIconData
     * is not configured).
     * Icons (the `name` attribute) require upload together with viewIconData; not implemented in
     * the current version, see docs [pending confirmation].
     */
    val DEFAULT_VIEW_DATA: String = SelfViewJson().apply {
        type = "LinearLayout"
        props = LinearLayoutProps().apply {
            id = "root"
            layout_width = "match_parent"
            layout_height = "match_parent"
            orientation = "vertical"
            backgroundColor = "#FF000000"
        }.toJson()
        children = listOf(
            SelfViewJson().apply {
                type = "TextView"
                props = TextViewProps().apply {
